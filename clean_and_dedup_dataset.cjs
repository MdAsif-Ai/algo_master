// Strict normalization key generator
function getNormKey(str) {
  let s = str.toLowerCase().trim();
  if (canonicalMap[s]) {
    s = canonicalMap[s].toLowerCase().trim();
  }
  // strip punctuation, spaces, common fluff words
  return s
    .replace(/\(.*?\)/g, '')
    .replace(/[^a-z0-9]/g, '');
}

const seenKeys = new Map(); // normKey -> problem object
